"""Generate the JSON editor's field contract from the authoritative DRF serializer."""

import json

from rest_framework import serializers

from elixir.serializers import ResourceSerializer, ResourceUpdateSerializer


# These serializers deliberately expose strings, not their model field objects.
STRING_SERIALIZERS = {
    'VersionSerializer', 'OperatingSystemSerializer', 'ToolTypeSerializer',
    'LanguageSerializer', 'CollectionIDSerializer', 'ElixirPlatformSerializer',
    'ElixirNodeSerializer', 'ElixirCommunitySerializer', 'PublicationTypeSerializer',
    'CreditTypeRoleSerializer', 'LinkTypeSerializer', 'DocumentationTypeSerializer',
    'EditPermissionAuthorSerializer',
}


def describe(field, *, constraints=False):
    result = {
        'required': field.required,
        'readOnly': field.read_only,
        'nullable': field.allow_null,
    }
    if isinstance(field, serializers.ListSerializer):
        result.update(kind='array', empty=field.allow_empty, item=describe(field.child, constraints=constraints))
    elif type(field).__name__ in STRING_SERIALIZERS:
        result.update(kind='string', blank=False)
    elif isinstance(field, serializers.BaseSerializer):
        # A new custom wire representation requires an explicit review, not a guess.
        if 'to_representation' in type(field).__dict__:
            raise ValueError(f'Review custom representation: {type(field).__name__}')
        result.update(kind='object', fields={name: describe(child, constraints=constraints) for name, child in field.fields.items()})
    elif isinstance(field, serializers.BooleanField):
        result.update(kind='boolean')
    elif isinstance(field, (serializers.IntegerField, serializers.FloatField)):
        result.update(kind='number')
    elif isinstance(field, (serializers.CharField, serializers.DateTimeField, serializers.SlugRelatedField)):
        result.update(kind='string', blank=getattr(field, 'allow_blank', False))
    else:
        raise ValueError(f'Review new field type: {type(field).__name__}')
    if constraints:
        for name, key in (('min_length', 'minLength'), ('max_length', 'maxLength'),
                          ('min_value', 'minimum'), ('max_value', 'maximum')):
            value = getattr(field, name, None)
            if value is not None:
                result[key] = value
    return result


def resource_contract(*, constraints=False):
    create = describe(ResourceSerializer(), constraints=constraints)
    update = describe(ResourceUpdateSerializer(), constraints=constraints)
    if create != update:
        raise ValueError('Create/update field shapes differ; review the editor contract.')
    return create


def render_contract():
    return (
        '// Generated by elixir.editor_contract.render_contract; do not edit.\n'
        '// Field shapes only. DRF validators and views remain authoritative.\n'
        'export const resourceContract = '
        + json.dumps(resource_contract(), indent=2)
        + ' as const;\n'
    )
